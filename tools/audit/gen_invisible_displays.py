"""Generates server_module/src/invisible_displays.h from the client's DBC files.

A creature whose model is an "invisible stalker" is on the server's visible list (the client
is sent it) but draws nothing: a player sees nobody there. The server doesn't load model file
names, so this reads CreatureDisplayInfo.dbc and CreatureModelData.dbc (extracted by
tools/setup/extract-data.sh into out/server/data/dbc) and lists every display id whose model is an
InvisibleStalker or InvisibleMan model.

Re-run when the client data changes (3.3.5a is frozen, so: practically never), then commit.

Usage: python3 -I tools/audit/gen_invisible_displays.py
"""

import pathlib
import shutil
import struct
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
DBC = ROOT / "out" / "server" / "data" / "dbc"
OUT = ROOT / "server_module" / "src" / "invisible_displays.h"
INVISIBLE_MODELS = ("invisiblestalker", "invisibleman")


TEMPLATE = """// Copyright 2026 The wow-llm-bots Authors. Licensed under GPL-2.0.
//
// GENERATED by tools/audit/gen_invisible_displays.py from the client's DBC files; don't edit.
// The @COUNT@ creature display ids whose model is an InvisibleStalker or InvisibleMan:
// the client draws nothing for them.

#ifndef MOD_LLM_BRAIN_INVISIBLE_DISPLAYS_H_
#define MOD_LLM_BRAIN_INVISIBLE_DISPLAYS_H_

#include <cstdint>

namespace llm_brain {

// Sorted.
inline constexpr uint32_t kInvisibleDisplays[] = {@IDS@};

}  // namespace llm_brain

#endif  // MOD_LLM_BRAIN_INVISIBLE_DISPLAYS_H_
"""


def load(name):
    data = (DBC / name).read_bytes()
    magic, count, _, record_size, _ = struct.unpack_from("<4s4I", data, 0)
    assert magic == b"WDBC", f"{name}: not a DBC file"
    records = [data[20 + i * record_size:20 + (i + 1) * record_size] for i in range(count)]
    return records, data[20 + count * record_size:]


def cstring(strings, offset):
    return strings[offset:strings.index(b"\0", offset)].decode("utf8", "replace")


def main():
    records, strings = load("CreatureModelData.dbc")
    model_path = {}
    for record in records:
        model_id, _, name_offset = struct.unpack_from("<3I", record, 0)
        model_path[model_id] = cstring(strings, name_offset).lower()
    displays = []
    for record in load("CreatureDisplayInfo.dbc")[0]:
        display_id, model_id = struct.unpack_from("<2I", record, 0)
        if any(m in model_path.get(model_id, "") for m in INVISIBLE_MODELS):
            displays.append(display_id)
    displays.sort()
    body = ", ".join(str(d) for d in displays)
    OUT.write_text(TEMPLATE.replace("@COUNT@", str(len(displays))).replace("@IDS@", body))
    if shutil.which("clang-format"):
        subprocess.run(["clang-format", "-i", str(OUT)], check=True)
    print(f"{len(displays)} invisible display ids -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
